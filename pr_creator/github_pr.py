from datetime import UTC, datetime

from github import Github, GithubException

from config import GITHUB_TOKEN
from database import Patch, Repo, get_session
from logger import get_logger
from notifications import send_pr_notification

logger = get_logger(__name__)


def get_github_client() -> Github:
    if not GITHUB_TOKEN:
        raise ValueError("GITHUB_TOKEN not set in .env")
    return Github(GITHUB_TOKEN)


def create_branch(repo, branch_name: str, base_sha: str):
    try:
        repo.create_git_ref(f"refs/heads/{branch_name}", base_sha)
        logger.info(f"Created branch: {branch_name}")
    except GithubException as e:
        if e.status == 422:
            logger.warning(f"Branch {branch_name} already exists — continuing")
        else:
            raise


def update_file_on_branch(repo, file_path: str, new_content: str, branch_name: str):
    try:
        current_file = repo.get_contents(file_path, ref=branch_name)
        repo.update_file(
            path=file_path,
            message="[PatchPilot] Fix Stripe API breaking change",
            content=new_content,
            sha=current_file.sha,
            branch=branch_name,
        )
        logger.info(f"Updated {file_path}")
    except GithubException as e:
        logger.error(f"Could not update {file_path}: {e.status}")
        raise


def build_pr_body(patches: list) -> str:
    files_list = "\n".join([f"- `{p.file_path}`" for p in patches])
    return f"""## PatchPilot — automated Stripe API fix

This PR was automatically generated by PatchPilot after detecting a breaking change in the Stripe API.

### Files updated
{files_list}

### What to do
1. Review the diff carefully
2. Run your test suite
3. Merge if everything looks good

> Always review auto-generated changes before merging.
"""


def create_pull_request(repo_db_id: int, patches: list) -> str | None:
    client = get_github_client()

    session = get_session()
    try:
        repo_record = session.query(Repo).filter_by(id=repo_db_id).first()
        if not repo_record:
            logger.warning(f"Repo id={repo_db_id} not found in database")
            return None
    finally:
        session.close()

    try:
        repo = client.get_repo(f"{repo_record.owner}/{repo_record.repo_name}")
    except GithubException as e:
        logger.error(f"Cannot access repo: {e.status}")
        return None

    default_branch = repo.default_branch
    base_sha = repo.get_branch(default_branch).commit.sha

    timestamp = datetime.now(tz=UTC).strftime("%Y%m%d-%H%M%S")
    branch_name = f"patchpilot/fix-stripe-{timestamp}"

    create_branch(repo, branch_name, base_sha)

    for patch in patches:
        if patch.patched_code:
            update_file_on_branch(
                repo, patch.file_path, patch.patched_code, branch_name
            )

    try:
        pr = repo.create_pull(
            title="[PatchPilot] Fix: Stripe API breaking change",
            body=build_pr_body(patches),
            head=branch_name,
            base=default_branch,
        )
        logger.info(f"PR created: {pr.html_url}")
        return pr.html_url
    except GithubException as e:
        logger.error(f"Failed to create PR: {e.status} — {e.data}")
        return None


def save_pr_url(patches: list, pr_url: str):
    session = get_session()
    try:
        for patch in patches:
            p = session.query(Patch).filter_by(id=patch.id).first()
            p.pr_url = pr_url
            p.status = "pr_opened"
        session.commit()
        logger.info(f"Saved PR URL to {len(patches)} patch record(s)")
    finally:
        session.close()


def run_pr_creator(repo_db_id: int, patches: list) -> str | None:
    patched = [p for p in patches if p.patched_code and p.status == "patched"]

    if not patched:
        logger.warning("No patched files ready for PR")
        return None

    logger.info(f"Creating PR for {len(patched)} file(s)")
    pr_url = create_pull_request(repo_db_id, patched)

    if pr_url:
        save_pr_url(patched, pr_url)

        session = get_session()
        try:
            repo = session.query(Repo).filter_by(id=repo_db_id).first()
            repo_url = repo.github_url if repo else "unknown"
        finally:
            session.close()

        for patch in patched:
            send_pr_notification(
                repo_url=repo_url,
                file_path=patch.file_path,
                pr_url=pr_url,
                api_name="Stripe",
            )

    return pr_url
